def to_unicode(ascii_braille: str, table: str) -> str:
    inv = {c: chr(0x2800 + i) for i, c in enumerate(table)}
    a = ascii_braille.upper().replace("{", "[").replace("}", "]").replace("~", "^")
    return "".join(inv.get(c, c) for c in a)
